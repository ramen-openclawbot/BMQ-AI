export type SalesCrmKey = keyof typeof salesCrm.vi;
export function salesCrmText(language: "en" | "vi", key: SalesCrmKey, values: Record<string, string | number> = {}) {
 return salesCrm[language][key].replace(/\{(\w+)\}/g, (token, name) => values[name] === undefined ? token : String(values[name]));
}
export function useSalesCrmMessages() {
 const { language } = useLanguage();
 return useCallback((key: SalesCrmKey, values?: Record<string, string | number>) => salesCrmText(language, key, values), [language]);
}

type SalesCrmNoticeValue = string | number | SalesCrmNotice | Array<string | number | SalesCrmNotice>;
// Feedback stores a typed UI message, never a translated business string. The canonical
// Vietnamese string remains available for existing status/tone checks.
export type SalesCrmNotice = { key: SalesCrmKey; values?: Record<string, SalesCrmNoticeValue> };
export const crmNotice = (key: SalesCrmKey, values?: SalesCrmNotice['values']): SalesCrmNotice => ({ key, values });
function renderNoticeValue(language: "en" | "vi", value: SalesCrmNoticeValue): string {
  if (Array.isArray(value)) return value.map((item) => renderNoticeValue(language, item)).join("; ");
  if (value === null || typeof value !== "object") return String(value);
  return renderCrmNotice(language, value);
}
export function renderCrmNotice(language: "en" | "vi", notice: string | SalesCrmNotice): string {
  if (typeof notice === "string") return notice;
  return salesCrmText(language, notice.key, Object.fromEntries(Object.entries(notice.values || {}).map(([k, v]) => [k, renderNoticeValue(language, v)])));
}
export class SalesCrmUiError extends Error {
  notice: SalesCrmNotice;
  constructor(key: SalesCrmKey, values?: SalesCrmNotice['values']) {
    const notice = crmNotice(key, values);
    super(renderCrmNotice("vi", notice));
    this.notice = notice;
  }
}
export function crmErrorNotice(error: unknown, fallback: SalesCrmKey = "Không rõ nguyên nhân"): string | SalesCrmNotice {
  if (error instanceof SalesCrmUiError) return error.notice;
  if (error && typeof error === "object" && "message" in error && error.message) return String(error.message);
  return crmNotice(fallback);
}

export function useSalesCrmFeedback() {
  const { language } = useLanguage();
  const [notice, setNotice] = useState<string | SalesCrmNotice>("");
  return [renderCrmNotice("vi", notice), setNotice, renderCrmNotice(language, notice)] as const;
}
